# ---- derived, so a pair can never drift apart -------------------------------------------------
def rows(a): return [r for r in a.strip('\n').split('\n')]
flipH = lambda g: [r[::-1] for r in g]
flipV = lambda g: list(reversed(g))
G = {k: rows(v) for k, v in I.items()}
G['arrow_right'] = flipH(G['arrow_left'])
G['caret_up'] = flipV(G['caret_down'])
G['tri_up'] = flipV(G['tri_down'])
G['trend_down'] = flipV(G['trend_up'])

def double(g): return [''.join(c * 2 for c in r) for r in g for _ in (0, 1)]

def check(name, g):
    errs = []
    if len(g) != 12 or any(len(r) != 12 for r in g): errs.append('not 12x12')
    for i in range(12):
        for x, y in [(i, 0), (i, 11), (0, i), (11, i)]:
            if g[y][x] == '#': errs.append(f'margin {x},{y}')
    lit = lambda x, y: 0 <= x < 12 and 0 <= y < 12 and g[y][x] == '#'
    xs = [x for y in range(12) for x in range(12) if g[y][x] == '#']
    ys = [y for y in range(12) for x in range(12) if g[y][x] == '#']
    # 24-scale centring rule: |centre - 11.5| <= 1  ->  in units, the bbox centre within 0.5 of 5.5
    cx = (min(xs) * 2 + max(xs) * 2 + 1) / 2; cy = (min(ys) * 2 + max(ys) * 2 + 1) / 2
    if abs(cx - 11.5) > 1: errs.append(f'off-centre x {cx}')
    if abs(cy - 11.5) > 1: errs.append(f'off-centre y {cy}')
    return errs

if __name__ == '__main__':
    bad = {k: e for k, g in G.items() for e in [check(k, g)] if e}
    if bad:
        for k, e in bad.items(): print(k, e)
        sys.exit(1)
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
    path = os.path.join(root, 'design-exports', 'macrosaurus-icons-24.json')
    art = json.load(open(path))
    missing = set(art['icons']) - set(G)
    if missing: print('missing', sorted(missing)); sys.exit(1)
    art['meta'] = dict(art.get('meta', {}), set='Handheld (35-reset direction C)', grid='12x12 doubled to 24x24',
                       source='tools/c-icons.py')
    art['icons'] = {k: double(G[k]) for k in sorted(art['icons'])}
    json.dump(art, open(path, 'w'), indent=1)
    print('wrote', len(art['icons']), 'icons')
