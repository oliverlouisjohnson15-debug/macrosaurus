FLIPS = {"arrow_right": ("arrow_left", "h"), "caret_down": ("caret_up", "v"), "tri_down": ("tri_up", "v"), "trend_down": ("trend_up", "v")}

def to24(rows):
    h, w = len(rows), len(rows[0])
    top, left = 1 + (10 - h) // 2, 1 + (10 - w) // 2
    g = [["."] * 12 for _ in range(12)]
    for y, r in enumerate(rows):
        for x, c in enumerate(r): g[top + y][left + x] = c
    out = []
    for r in g:
        line = "".join(c * 2 for c in r)
        out += [line, line]
    return out

if __name__ == "__main__":
    icons = {n: to24(a) for n, a in ART.items()}
    for n, (src, how) in FLIPS.items():
        icons[n] = [r[::-1] for r in icons[src]] if how == "h" else icons[src][::-1]
    root = os.path.join(os.path.dirname(__file__), "..")
    meta = {"grid": 24, "sizes": [24, 48], "colour": "currentColor", "set": "Macrosaurus pixel family (35-reset)",
            "source": "tools/pixel-icons.py", "credit": "Drawn for Macrosaurus; outline weight after pixelarticons (MIT, Gerrit Halfmann)"}
    json.dump({"meta": meta, "icons": dict(sorted(icons.items()))}, open(os.path.join(root, "design-exports", "macrosaurus-icons-24.json"), "w"), indent=1)
    print(len(icons), "icons")
