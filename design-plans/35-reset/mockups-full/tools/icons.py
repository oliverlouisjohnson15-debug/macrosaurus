"""Macrosaurus pixel icon family (35-reset, full mockup).

One grid: 12x12 cells, each cell 2px at the 24px size (4px at 48). One-cell outline, square
joins, solid fill only for small marks (a dot, an arrowhead). Drawn for this app; the outline
weight and corner treatment follow pixelarticons (MIT, Gerrit Halfmann) so the two families can
sit together. '#' is ink, '.' is empty. Every row is exactly 12 cells.
"""
I = {}
def d(name, art):
    rows = [r for r in art.strip('\n').split('\n')]
    assert len(rows) == 12, (name, len(rows))
    for r in rows: assert len(r) == 12, (name, r)
    I[name] = rows

